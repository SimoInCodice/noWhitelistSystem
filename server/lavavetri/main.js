var worksInProgress = {}

function getNextSpotWindow(source, callback) {
    let work = worksInProgress[source]
    if (work) {
        let job = windowsCleaningSpots[work.job]
        if (Object.keys(work.realizedSteps).length < work.stepsToRealize) {
            let nextStep = (!job.sessions) ? Math.floor(Math.random() * Object.keys(job.steps).length) : Math.floor(Math.random() * Object.keys(job.sessions[work.currentSession].steps).length)
            if (!work.realizedSteps[nextStep]) {
                callback(nextStep)
            } else {
                getNextSpotWindow(source, callback)
            }
        } else {
            callback(-1)
        }
    }
}

onNet('lilabyte_windowsCleaner:server:startCurrentJob', (spotName) => {
    let source = global.source
    if (!worksInProgress[source]) {
        let job = windowsCleaningSpots[spotName]
        if (job.sessions) {
            let freeSession = -1
            Object.values(job.sessions).forEach(session => {
                let isSessionBusy = Object.values(worksInProgress).find(work => work.job == spotName && work.currentSession == session.id) || false
                freeSession = (freeSession >= 0) ? freeSession : (!isSessionBusy) ? session.id : -1
            })
            if (freeSession >= 0) {
                worksInProgress[source] = {
                    job: spotName,
                    nextStep: -1,
                    lastStep: -1,
                    reward: 0,
                    stepsToRealize: Math.floor(Math.random() * (job.maxStepsToRealize - job.minStepsToRealize)) + job.minStepsToRealize,
                    realizedSteps: {},
                    currentSession: freeSession,
                    startTimestamp: new Date().getTime()
                }
                emitNet('lilabyte_windowsCleaner:startCurrentJobCallback', source, spotName, true, freeSession)
                getNextSpotWindow(source, (nextStep) => {
                    worksInProgress[source].nextStep = nextStep
                    emitNet('lilabyte_windowsCleaner:setNextStep', source, {lastStep: -1, nextStep: nextStep})
                })
            } else {
                // Notification about that there is no free slots to work
            }
        }
    } else {
        // Notification about that player already started a job
    }
})

onNet('lilabyte_windowsCleaner:server:stopCurrentJob', (spotName) => {
    let source = global.source
    if (worksInProgress[source]) {
        if (worksInProgress[source].reward > 0) {
            // Event to add money - money count is worksInProgress[source].reward
            // Notification about reward
        }
        delete worksInProgress[source]
        emitNet('lilabyte_windowsCleaner:stopCurrentJobCallback', source, spotName, true)
    } else {
        // Notification about that player has not started a job
    }
})

onNet('lilabyte_windowsCleaner:server:realizeStep', (spotName, step, data) => {
    let source = global.source
    if (worksInProgress[source] && worksInProgress[source].job == spotName) {
        if (worksInProgress[source].nextStep == step) {
            let currentReward = 0
            worksInProgress[source].lastStep = step
            worksInProgress[source].realizedSteps[step] = true
            currentReward = windowsCleaningSpots[spotName].sessions[worksInProgress[source].currentSession].steps[step].reward
            worksInProgress[source].reward = worksInProgress[source].reward + currentReward
            getNextSpotWindow(source, (nextStep) => {
                worksInProgress[source].nextStep = nextStep
                emitNet('lilabyte_windowsCleaner:setNextStep', source, {lastStep: worksInProgress[source].lastStep, nextStep: nextStep})
            })
        }
    } else {
        // Notification about that player has not started a job
    }
})

on("playerDropped", () => {
    let source = global.source
    delete worksInProgress[source]
});